// No network: the models are stubs. Run with `npm test`.
import assert from 'node:assert/strict';
import { parseImageStream, recordsOfKind, decodeMaskToSVGPath } from '@meta-sam/parser';
import { provenance, readImage } from '../src/provenance.mjs';
import { createLens } from '../src/lens.mjs';
import { parseJson } from '../src/meta.mjs';

// --- tiny hand-built image files ---
const be32 = n => [(n >>> 24) & 255, (n >>> 16) & 255, (n >>> 8) & 255, n & 255];
const bytes = s => [...Buffer.from(s, 'latin1')];
function png(width, height, extraChunks = []) {
  const chunk = (type, body) => [...be32(body.length), ...bytes(type), ...body, 0, 0, 0, 0];
  return new Uint8Array([
    0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
    ...chunk('IHDR', [...be32(width), ...be32(height), 8, 6, 0, 0, 0]),
    ...extraChunks.flatMap(([t, b]) => chunk(t, b)),
    ...chunk('IDAT', bytes('Midjourney trainedAlgorithmicMedia')), // pixel data must never count as a label
    ...chunk('IEND', []),
  ]);
}
function jpeg(width, height, app = []) {
  const seg = (marker, body) => [0xff, marker, ((body.length + 2) >> 8) & 255, (body.length + 2) & 255, ...body];
  return new Uint8Array([
    0xff, 0xd8,
    ...app.flatMap(([m, b]) => seg(m, b)),
    ...seg(0xc0, [8, (height >> 8) & 255, height & 255, (width >> 8) & 255, width & 255, 1, 1, 0x11, 0]),
    0xff, 0xda, 0, 2, ...bytes('Stable Diffusion'), 0xff, 0xd9, // scan data: never read
  ]);
}

// --- provenance: certain labels from the file, never from pixels ---
let p = provenance(png(640, 480));
assert.equal(p.type, 'png'); assert.equal(p.width, 640); assert.equal(p.height, 480);
assert.equal(p.aiLabel, false, 'pixel data that happens to spell a label is ignored');

p = provenance(png(512, 512, [['tEXt', bytes('parameters\0a cat, 4k, Steps: 30')]]));
assert.equal(p.aiLabel, true); assert.ok(p.signals.some(s => s.kind === 'generator-settings'));

p = provenance(jpeg(1200, 800, [[0xe1, bytes('http://ns.adobe.com/xap/1.0/\0<Iptc4xmpExt:DigitalSourceType>http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia</Iptc4xmpExt:DigitalSourceType>')]]));
assert.equal(p.type, 'jpeg'); assert.equal(p.width, 1200); assert.equal(p.height, 800);
assert.equal(p.aiLabel, true); assert.match(p.signals.find(s => s.kind === 'ai-source-type').detail, /generated by AI/);

p = provenance(jpeg(100, 100, [[0xe1, bytes('Exif\0\0 compositeWithTrainedAlgorithmicMedia')]]));
assert.match(p.signals.find(s => s.kind === 'ai-source-type').detail, /edited or combined/);

p = provenance(jpeg(100, 100, [[0xeb, bytes('JP\0\0jumb c2pa.manifest')]]));
assert.equal(p.contentCredentials, true); assert.equal(p.aiLabel, false, 'Content Credentials alone do not mean AI');

p = provenance(jpeg(100, 100));
assert.equal(p.aiLabel, false, 'a JPEG with only scan data mentioning a tool is not labelled');
assert.equal(readImage(new Uint8Array([1, 2, 3])).type, 'unknown');

// --- the lens: code combines the file's facts with the model's careful opinion ---
const answer = obj => async () => JSON.stringify(obj);
const noSam = async () => [];
const photo = jpeg(1000, 500);
const sign = { what: 'left hand', why: 'The hand has six fingers.', box: [100, 200, 300, 400] };

let r = await createLens({ ask: answer({ verdict: 'likely_ai', confidence: 0.85, kind: 'photo', summary: 'Several signs of AI.', signs: [sign], harm: { harmful: false, category: 'none', reason: '' } }), segment: noSam }).assess(photo);
assert.equal(r.verdict, 'likely_ai'); assert.equal(r.label, 'Likely AI-generated'); assert.equal(r.certain, false);
assert.deepEqual(r.signs[0].box, [100, 200, 300, 400]);

r = await createLens({ ask: answer({ verdict: 'likely_ai', confidence: 0.4, summary: 'Maybe.', signs: [] }), segment: noSam }).assess(photo);
assert.equal(r.verdict, 'cant_tell', 'a weak guess is reported as "can\'t tell"');

r = await createLens({ ask: answer({ verdict: 'no_ai_signs', confidence: 0.8, summary: 'A studio photo of fruit.', signs: [{ what: 'skin', why: 'Natural pores.', box: [1, 1, 50, 50] }] }), segment: noSam }).assess(photo);
assert.equal(r.verdict, 'no_ai_signs'); assert.equal(r.label, 'No signs of AI found');
assert.match(r.summary, /^A studio photo of fruit\. That doesn't prove it's real/);
assert.equal(r.signs.length, 0, 'no "looks real" evidence is ever listed');
r = await createLens({ ask: answer({ verdict: 'likely_authentic', confidence: 0.95, signs: [] }), segment: noSam }).assess(photo);
assert.equal(r.verdict, 'no_ai_signs', 'an "authentic" answer is never passed on as proof');

r = await createLens({ ask: async () => { throw new Error('down'); }, segment: noSam }).assess(photo);
assert.equal(r.verdict, 'unavailable', 'a model failure never says "authentic"'); assert.match(r.summary, /doesn't mean it's real or fake/);

r = await createLens({ ask: async () => 'I think it looks fine!', segment: noSam }).assess(photo);
assert.equal(r.verdict, 'unavailable', 'junk instead of JSON is a failure, not a verdict');

const labelled = jpeg(800, 800, [[0xe1, bytes('xmp trainedAlgorithmicMedia')]]);
r = await createLens({ ask: answer({ verdict: 'likely_authentic', confidence: 0.9, signs: [] }), segment: noSam }).assess(labelled);
assert.equal(r.verdict, 'labelled_ai', "the file's own label beats the model's opinion"); assert.equal(r.certain, true);
r = await createLens({ ask: answer({ verdict: 'likely_authentic', confidence: 0.9, signs: [{ what: 'skin', why: 'Natural pores.', box: [1, 1, 50, 50] }] }), segment: noSam }).assess(labelled);
assert.equal(r.signs.length, 0, 'reasons it "looks real" are not shown under an AI label');

r = await createLens({ ask: answer({ verdict: 'maybe', confidence: 0.9 }), segment: noSam }).assess(photo);
assert.equal(r.verdict, 'cant_tell', 'an unknown verdict becomes "can\'t tell"');
r = await createLens({ ask: answer({ verdict: 'likely_ai', confidence: 7, signs: [{ what: 'x', why: 'odd', box: [-50, 20, 2000, 10] }, { why: '' }], harm: { harmful: true, category: 'made_up' } }), segment: noSam }).assess(photo);
assert.equal(r.verdict, 'likely_ai'); assert.equal(r.confidence, 1);
assert.equal(r.signs.length, 1, 'a sign with no reason is dropped'); assert.equal(r.signs[0].box, null, 'an inverted box is dropped');
assert.equal(r.harm.harmful, false, 'an unknown harm category is not counted as harm');

r = await createLens({ ask: answer({ verdict: 'cant_tell', confidence: 0.5, signs: [], harm: { harmful: true, category: 'doxxing', reason: 'A home address is visible.' } }), segment: noSam }).assess(photo);
assert.equal(r.harm.harmful, true); assert.equal(r.harm.category, 'doxxing');

// SAM outlines refine the boxes; a SAM failure keeps Muse Spark's boxes.
let asked;
r = await createLens({ ask: answer({ verdict: 'likely_ai', confidence: 0.9, signs: [sign] }), segment: async (req) => { asked = req; return [{ index: 0, box: [110, 210, 290, 390], path: { d: 'M0 0L1 1', x: 110, y: 105, w: 180, h: 90 } }]; } }).assess(photo);
assert.equal(asked.width, 1000); assert.equal(asked.height, 500); assert.equal(asked.signs[0].index, 0);
assert.deepEqual(r.signs[0].box, [110, 210, 290, 390]); assert.equal(r.signs[0].path.d, 'M0 0L1 1');
r = await createLens({ ask: answer({ verdict: 'likely_ai', confidence: 0.9, signs: [sign] }), segment: async () => { throw new Error('sam down'); } }).assess(photo);
assert.deepEqual(r.signs[0].box, [100, 200, 300, 400]);

r = await createLens({ ask: answer({}), segment: noSam }).assess(new Uint8Array([0, 1, 2, 3]));
assert.equal(r.verdict, 'unavailable'); assert.match(r.summary, /not a JPEG, PNG or WebP/);

assert.deepEqual(parseJson('Sure: ```json\n{"a":1}\n``` done'), { a: 1 });

// --- Meta's SAM parser reads SAM 3.1 output (sample line from the Meta docs) ---
const line = "<0f>0<|box;x1=211;y1=228;x2=270;y2=254;w=320;h=334|><|mask;x=0;y=0;data=27,60,~!!!!M!0c[0o91w?q1!pIH4pPRVp2B3'7`e.ioeAf6-k/#Xd8%dX9x(|>";
async function* events() {
  yield { type: 'response.output_text.delta', delta: line, output_index: 0, content_index: 0, item_id: 'm' };
  yield { type: 'response.output_text.done', text: line, output_index: 0, content_index: 0, item_id: 'm' };
  yield { type: 'response.completed', response: { status: 'completed' } };
}
const seg = await parseImageStream(events()).finalResult;
const [mask] = recordsOfKind(seg.records, 'mask');
assert.equal(mask.mask.width, 60); assert.equal(mask.mask.height, 27);
assert.match(decodeMaskToSVGPath(mask.mask), /^M/);

console.log('Argus Lens checks passed.');
